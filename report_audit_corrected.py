#!/usr/bin/env python3
"""
生成【修正解读版】审计报告 → 推送到 Hermes TG bot

为什么需要修正版:
  原始报告把六种信号的完整度求"做多均值", 但方法论决定了各列可信度不同:
  - 📈爬升/📉阴跌 (60根收盘价窗口): 与生产口径最接近 → 完整度<100% = 确定性漏报
  - 🚀暴涨/🩸暴跌/3m放量: 生产在 WS 流式 tick 上判断(含未收盘K线),
    审计只能用已收盘K线 → 反推值是【下界】, 数据完整时必然 >100%
  所以只有"爬升"列可用于判定数据完整性, 暴涨类的>100%不代表数据完整。
"""
import sys
sys.path.insert(0, '/root/CryptoMonitor')
from push_report_to_tg import load_hermes_tg, send, split_msg
import asyncio

# 爬升信号: (应报=K线反推下界, 实报=DB入库)
CLIMB = {
    '09-19': (2400, 293), '09-20': (788, 498), '09-21': (1550, 439),
    '09-22': (1083, 533), '09-23': (1246, 650), '09-24': (593, 428),
    '09-25': (1357, 1175), '09-26': (764, 1184), '09-27': (514, 760),
    '09-28': (329, 421),
}

lines = []
A = lines.append
A("🔍 信号完整性审计 (9-19~9-28, 554个币, 三种信号全覆盖)")
A("耗时4.5h | 11278次请求 | 0次限流 | 生产服务全程无影响")
A("")
A("━━━━━━━━━━━━━━━━━━━━━")
A("📊 核心指标: 📈爬升信号完整度")
A("(爬升用60根收盘价窗口, 与生产口径一致 → <100%即确定性漏报)")
A("━━━━━━━━━━━━━━━━━━━━━")
A(f"{'日期':<7}{'应报':>6}{'实报':>6}{'完整度':>7}  判定")
ok_days, bad_days = [], []
for d, (sh, ac) in CLIMB.items():
    pct = ac / sh * 100
    if pct >= 100:
        v = '✅完整'; ok_days.append(d)
    elif pct >= 85:
        v = '🟡基本可信'; ok_days.append(d)
    elif pct >= 60:
        v = '⚠️残缺'; bad_days.append(d)
    else:
        v = '❌严重残缺'; bad_days.append(d)
    A(f"{d:<7}{sh:>6}{ac:>6}{pct:>6.0f}%  {v}")

A("")
A("━━━━━━━━━━━━━━━━━━━━━")
A("🎯 结论")
A("━━━━━━━━━━━━━━━━━━━━━")
A(f"✅ 可信日期: {' '.join(ok_days)}")
A(f"❌ 残缺日期: {' '.join(bad_days)}")
A("")
A("💥 关键发现 (比预想严重):")
A("1. 9-19 只有12%完整 — 该日几乎无有效数据")
A("2. 9-21/9-22/9-23 仅28%~52% — 一半以上信号丢失")
A("3. 9-26起才真正100%完整 (之前判断'9-25起可信'偏乐观)")
A("4. 9-23漏报最狠: 623个币有漏报, ILV/ELSA/龙虾等应报13~16条实报0条")
A("")
A("🧠 根因: rolling_window是内存deque")
A("  WS反复重连(NoneType崩溃367次) + 内存节流冻结")
A("  → 窗口断档/清零 → 该报的信号没触发")
A("  修复落地: 9-24 14:52 + 16:07 (断线归零)")
A("")
A("⚠️ 对回测结论的影响:")
A("  之前基于9-19~9-27的回测全部被污染")
A("  例: 波段口径B变体曾报+243U(9-19~9-27)")
A("     改用干净窗口9-25~9-28 → 三个变体全亏")
A("     (当天收盘平-677U/跨天持仓-937U/移动止盈-371U)")
A("  → 那些'正期望'是残缺数据的幸存者偏差")
A("")
A("📌 方法论声明:")
A("  🚀暴涨/暴跌/3m放量 列显示>100%不代表数据完整 —")
A("  生产在流式tick上判断(含未收盘K线), 审计只能用已收盘K线,")
A("  故反推值为【下界】, 完整时必然>100%。判定完整性只看爬升列。")
A("")
A("📋 建议:")
A("  • 回测只用 9-26 之后的数据 (目前仅3天, 不够)")
A("  • 从现在开始让系统干净攒数据, 10月中旬有20+天再做严肃回测")
A("  • 审计脚本已入库: audit_signal_completeness.py (随时可自查某天)")

text = '\n'.join(lines)
print(text)
print(f"\n===== 共 {len(text)} 字符 =====")

async def go():
    tok, cid = load_hermes_tg()
    parts = split_msg(text, 4000)
    print(f"切 {len(parts)} 段")
    for i, p in enumerate(parts, 1):
        head = f"🐾 ({i}/{len(parts)})\n" if len(parts) > 1 else ''
        if await send(tok, cid, head + p):
            print(f"  段{i}: ✅")
        else:
            print(f"  段{i}: ❌ 中止"); return 1
        await asyncio.sleep(1.0)
    print("全部送达 ✅")
    return 0

if __name__ == '__main__':
    if '--dry' not in sys.argv:
        sys.exit(asyncio.run(go()))
